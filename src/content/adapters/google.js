/**
 * Google Search — result snippets and the site-labelled "AI Overview".
 *
 * Snippets are short, so the detector's short-text caps keep most of them
 * visible unless evidence is strong. The AI Overview is labelled as AI by
 * Google itself and is handled via `findLabeledAI` (toggle:
 * "Block content labelled as AI by the site").
 */

const RESULT_CONTAINER = '.MjjYud, div.g, [data-sokoban-container]';
const STOP_IDS = new Set(['rso', 'search', 'center_col', 'rcnt', 'main', 'cnt', 'appbar']);

function findOverviewContainer(heading) {
  let el = heading;
  for (let i = 0; i < 8 && el && el.parentElement; i++) {
    el = el.parentElement;
    if (STOP_IDS.has(el.id) || el.tagName === 'BODY' || el.tagName === 'MAIN') return null;
    if (el.querySelector('#rso')) return null;
    if (el.textContent.length >= 300) return el;
  }
  return null;
}

export default {
  id: 'google',
  name: 'Google Search',
  matches: (host) => /^(www\.)?google\.[a-z.]{2,6}$/.test(host),
  useGeneric: false,
  unitSelectors: ['div.VwiC3b', '[data-sncf="1"]', 'div[data-content-feature="1"]'],
  excludeSelectors: ['cite', '[role="heading"]', 'h3', '.LEwnzc'],
  getBlockTarget(unit) {
    try {
      return unit.closest(RESULT_CONTAINER) || unit;
    } catch {
      return unit;
    }
  },
  findLabeledAI(root) {
    const scope = root.querySelectorAll ? root : root.ownerDocument;
    const found = [];
    const headings = scope.querySelectorAll('h1, h2, [role="heading"]');
    for (const h of headings) {
      const text = h.textContent.trim().toLowerCase();
      if (text !== 'ai overview' && text !== 'ai overviews') continue;
      const container = findOverviewContainer(h);
      if (container) found.push({ element: container, label: 'Google "AI Overview" (generated by AI)' });
    }
    return found;
  },
};
